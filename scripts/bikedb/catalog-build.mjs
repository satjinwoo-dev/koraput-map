const VALUE_GROUPS = ["engine", "motor", "battery", "transmission", "chassis", "emission", "fuel"];
const ICE = ["ice_manual", "ice_cvt"];
const FIELD_BY_PATH = new Map(Contract.FIELDS.map((f) => [f.path, f]));

// ----------------------------------------------------------------------------
// Strict SI (conversions: SI_UNITS in bundle-contract.js)
// ----------------------------------------------------------------------------
/**
 * A sourced quantity { v, u, tol?, … } in SI. When the unit changes, the
 * figure as published is kept under `published` for human review.
 * @param {any} q            { v: number|number[], u: string, tol?, src, conf, … }
 * @param {string} unit      its published unit
 */
export function quantityToSI(q, unit) {
    const si = Contract.siUnit(unit);
    const out = { ...q, v: Contract.toSI(q.v, unit), u: si };
    if (q.tol !== undefined) out.tol = Contract.toSI(q.tol, unit);
    if (si !== unit) out.published = q.tol !== undefined ? { v: q.v, u: unit, tol: q.tol } : { v: q.v, u: unit };
    return out;
}

/** A prior { mean, sigma, u, … } in SI, with the published figures when the unit changes. */
export function priorToSI(p, unit) {
    const si = Contract.siUnit(unit);
    const out = { ...p, mean: Contract.toSI(p.mean, unit), sigma: Contract.toSI(p.sigma, unit), u: si };
    if (si !== unit) out.published = { mean: p.mean, sigma: p.sigma, u: unit };
    return out;
}

/** A digitised curve in SI: angular speed in rad/s, values in N*m or W. */
export function curveToSI(c) {
    const out = { ...c, omegaStart: Contract.toSI(c.rpmStart, "rpm"), omegaStep: Contract.toSI(c.rpmStep, "rpm"), scale: Contract.toSI(c.scale, c.u), u: Contract.siUnit(c.u),
        published: { rpmStart: c.rpmStart, rpmStep: c.rpmStep, scale: c.scale, u: c.u } };
    delete out.rpmStart;
    delete out.rpmStep;
    return out;
}

/** One value group (engine, chassis …) with every quantity and prior in SI; categorical values unchanged. */
function groupToSI(g, node) {
    /** @type {Record<string, any>} */
    const out = {};
    for (const [k, v] of Object.entries(node)) {
        const f = FIELD_BY_PATH.get(`${g}.${k}`);
        if (!f) out[k] = v;                                  // fuel.compat: fuel codes and statuses, no units
        else if (f.type === "q" || f.type === "qa") out[k] = quantityToSI(v, f.unit);
        else if (f.type === "p") out[k] = priorToSI(v, f.unit);
        else out[k] = v;
    }
    return out;
}

/** A fuel-grade row in SI: lhv J/m3, density kg/m3, typicalRon 1. */
function gradeToSI(g) {
    const out = { ...g };
    for (const k of ["lhv", "density", "typicalRon"]) if (g[k]) out[k] = quantityToSI(g[k], g[k].u);
    return out;
}

/** Sources of `list` whose id is in `ids`, in their original order. */
const usedSources = (list, ids) => (list || []).filter((s) => ids.has(s.id));

/**
 * The bundle a phone downloads, in strict SI: every quantity converted (the
 * figure as published kept under `published`), priors resolved through the
 * class default, the fuel-advice decision made by the contract, the reference
 * data the physics needs, and `image_url` for the bike picker (null until a
 * picture is sourced). Self-contained: once fetched it works offline.
 * @param {any} b          validated variant or class default
 * @param {any} classDef   the class default for b.classKey (b itself for a default)
 * @param {import("../../public/js/bikedb/bundle-contract.js").RefTables & Record<string, any>} ref
 * @param {any} [calibration]  the class's fleet calibration (data/bikes/calibration/): its real-riding
 *                             overhead and evidence go into the bundle as `calibration` (roadmap Step 11)
 */
export function makeRuntimeBundle(b, classDef, ref, calibration = null) {
    const isVariant = b.kind === "variant";
    /** @type {Record<string, any>} */
    const rt = {
        format: BUNDLE_FORMAT,
        schemaVersion: b.schemaVersion,
        id: b.id,
        kind: b.kind,
        classKey: b.classKey,
        segment: b.segment,
        powertrain: b.powertrain,
        units: "SI",
        identity: b.identity,
        image_url: b.image ? b.image.url : null,
        sources: b.sources
    };
    if (b.image) rt.image = b.image;                         // the picture's provenance (src, credit)
    for (const g of VALUE_GROUPS) if (b[g] !== undefined && b[g] !== null) rt[g] = groupToSI(g, b[g]);
    if (b.curves) rt.curves = Object.fromEntries(Object.entries(b.curves).map(([k, c]) => [k, curveToSI(c)]));
    if (Array.isArray(b.notes) && b.notes.length) rt.notes = b.notes;

    // Priors: the variant's own, else the class default's (marked inherited; their
    // src refers to classDefault.sources, so ids can never collide with the variant's).
    const priors = {};
    const inheritedSrc = new Set();
    for (const f of Contract.FIELDS) {
        if (!f.path.startsWith("priors.") || !f.allow.includes(b.powertrain)) continue;
        const key = f.path.slice("priors.".length);
        const own = b.priors && b.priors[key];
        if (own) priors[key] = priorToSI(own, f.unit);
        else if (isVariant && classDef.priors && classDef.priors[key]) {
            priors[key] = { ...priorToSI(classDef.priors[key], f.unit), inherited: true };
            inheritedSrc.add(classDef.priors[key].src);
        }
    }
    rt.priors = priors;
    // Fleet calibration (roadmap Step 11): the real-riding overhead learned with the class's priors
    // (dimensionless; its src is the class default's "fleet-calibration" source).
    if (calibration && ICE.includes(b.powertrain)) rt.calibration = { date: calibration.date, tanks: calibration.tanks, riders: calibration.riders, overhead: { ...calibration.overhead } };
    if (isVariant) rt.classDefault = { id: classDef.id, sources: usedSources(classDef.sources, inheritedSrc) };

    if (ICE.includes(b.powertrain)) {
        // The fuel-safety decision, made once here by the contract. The app shows
        // a fuel as recommended only if it's in this list.
        rt.fuelAdvice = {
            minConf: Contract.ADVISE_MIN_CONF,
            advisable: ref.fuelGrades.grades.map((g) => g.code).filter((code) => Contract.isFuelAdvisable(b, code, ref))
        };
        const gradeSrc = new Set(ref.fuelGrades.grades.flatMap((g) => ["lhv", "density", "typicalRon"].filter((k) => g[k]).map((k) => g[k].src)));
        rt.reference = { fuelGrades: { sources: usedSources(ref.fuelGrades.sources, gradeSrc), grades: ref.fuelGrades.grades.map(gradeToSI) } };
        if (b.emission) {
            const std = ref.emissionStandards.standards.find((s) => s.code === b.emission.standard.v);
            const obd = b.emission.obd ? ref.emissionStandards.obdLevels.find((o) => o.code === b.emission.obd.v) : null;
            const ids = new Set([std && std.src, obd && obd.src].filter(Boolean));
            /** @type {Record<string, any>} */
            const em = { sources: usedSources(ref.emissionStandards.sources, ids), standard: std };
            if (obd) em.obd = obd;
            rt.reference.emission = em;
        }
    }
    return rt;
}

