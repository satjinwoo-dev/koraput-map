/**
 * JSON with object keys sorted (code-unit order) at every level and no
 * whitespace. Array order is kept (it carries meaning: gear ratios, sources).
 * Throws on values JSON can't represent faithfully.
 * @param {unknown} value
 * @returns {string}
 */
export function canonicalJson(value) {
    if (value === null) return "null";
    switch (typeof value) {
        case "string": return JSON.stringify(value);
        case "boolean": return value ? "true" : "false";
        case "number":
            if (!Number.isFinite(value)) throw new BuildError(`cannot serialise ${value}`);
            return JSON.stringify(value);
        case "object": {
            if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
            const keys = Object.keys(value).sort();
            return `{${keys.map((k) => {
                if (value[k] === undefined) throw new BuildError(`undefined value at key "${k}"`);
                return `${JSON.stringify(k)}:${canonicalJson(value[k])}`;
            }).join(",")}}`;
        }
        default: throw new BuildError(`cannot serialise a ${typeof value}`);
    }
}

export const sha256 = (text) => crypto.createHash("sha256").update(text, "utf8").digest("hex");
export const shortHash = (text) => sha256(text).slice(0, HASH_CHARS);
export const gzipSize = (text) => zlib.gzipSync(Buffer.from(text, "utf8"), { level: 9 }).length;

