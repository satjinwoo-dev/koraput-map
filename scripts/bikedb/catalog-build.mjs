// Build pipeline for the bike catalogue (Step 3). The CLI is scripts/build-bike-catalog.mjs.
//
//   data/bikes/**.json  ──validate──►  runtime bundles  ──►  public/bikedb/bundles/<hash>.json
//                                            │          ──►  public/bikedb/catalog.json
//                                            └────────────►  build/bikedb/bikes.sqlite   (lib/bikedb/schema.sql)
//
// Rules:
//   * Nothing is written unless the whole catalogue validates (bundle-contract.js).
//     Files in data/bikes/pending/ are never built.
//   * Same input → same output. Output JSON is canonical (sorted keys, no
//     whitespace), with no timestamps, so catalog.json and every bundle are
//     byte-identical across builds and machines. bikes.sqlite is byte-identical
//     for the same SQLite version.
//   * A bundle's file name is the start of the SHA-256 of its bytes, so it can be
//     cached forever: changed data means a new name.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import zlib from "node:zlib";
import { createRequire } from "node:module";
import { ROOT, DATA, Contract, loadCatalog } from "./load-catalog.mjs";

const require = createRequire(import.meta.url);
/** @type {typeof import("../../public/js/bikedb/catalog-search.js")} */
export const Search = require("../../public/js/bikedb/catalog-search.js");

export const BUNDLE_FORMAT = "mapunite-bike-bundle/1";
export const DB_FORMAT = 2;                       // = PRAGMA user_version in lib/bikedb/schema.sql
export const HASH_CHARS = 16;                     // 64 bits of SHA-256, hex (safe on case-insensitive file systems)
export const CATALOG_BUDGET_GZIP = 300 * 1024;    // plan: catalog.json under 300 KB gzipped
export const BUNDLE_PATH = "bundles/{hash}.json";
export const SCHEMA_SQL = path.join(ROOT, "lib", "bikedb", "schema.sql");
export const DEFAULT_PUBLIC_DIR = path.join(ROOT, "public", "bikedb");
export const DEFAULT_DB_FILE = path.join(ROOT, "build", "bikedb", "bikes.sqlite");
const GITIGNORE = "# Generated by scripts/build-bike-catalog.mjs from data/bikes/. Don't edit or commit.\n*\n";
const BUNDLE_FILE_RE = new RegExp(`^[0-9a-f]{${HASH_CHARS}}\\.json$`);

export class BuildError extends Error {
    /** @param {string} message @param {string[]} [details] */
    constructor(message, details = []) {
        super(details.length ? `${message}\n  ${details.join("\n  ")}` : message);
        this.name = "BuildError";
        this.details = details;
    }
}

