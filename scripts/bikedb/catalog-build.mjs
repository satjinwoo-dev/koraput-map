/** Write via a temp file + rename, so a reader never sees half a file. */
function writeAtomic(file, text) {
    const tmp = `${file}.tmp-${process.pid}`;
    fs.writeFileSync(tmp, text);
    fs.renameSync(tmp, file);
}

/**
 * Write catalog.json and bundles/<hash>.json. Bundles go first and catalog.json
 * last, so a catalogue never points at a bundle that isn't there yet.
 * Unchanged bundles aren't rewritten. With prune (the default), bundle files
 * that no longer belong to the catalogue are removed, so the folder is exactly
 * the build output.
 * @param {ReturnType<typeof buildArtifacts>} art
 * @param {string} dir
 * @param {{ prune?: boolean }} [opts]
 */
export function writePublic(art, dir, { prune = true } = {}) {
    const bdir = path.join(dir, "bundles");
    fs.mkdirSync(bdir, { recursive: true });
    const gi = path.join(dir, ".gitignore");
    if (!fs.existsSync(gi)) fs.writeFileSync(gi, GITIGNORE);
    let written = 0, unchanged = 0, pruned = 0, bundleBytes = 0;
    const keep = new Set();
    for (const b of art.bundles) {
        const name = `${b.hash}.json`;
        keep.add(name);
        bundleBytes += Buffer.byteLength(b.bytes);
        const file = path.join(bdir, name);
        if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === b.bytes) { unchanged++; continue; }
        writeAtomic(file, b.bytes);
        written++;
    }
    writeAtomic(path.join(dir, "catalog.json"), art.catalog.bytes);
    if (prune) {
        for (const f of fs.readdirSync(bdir)) {
            const stale = (BUNDLE_FILE_RE.test(f) && !keep.has(f)) || /\.json\.tmp-\d+$/.test(f);
            if (stale) { fs.rmSync(path.join(bdir, f)); pruned++; }
        }
    }
    return { written, unchanged, pruned, bundleBytes, catalogBytes: Buffer.byteLength(art.catalog.bytes), catalogGzip: art.catalog.gzipBytes };
}

/**
 * Compare public/bikedb/ with a fresh build. Returns a list of differences.
 * @param {ReturnType<typeof buildArtifacts>} art
 * @param {string} dir
 */
export function diffPublic(art, dir) {
    const diffs = [];
    const cat = path.join(dir, "catalog.json");
    if (!fs.existsSync(cat)) diffs.push("catalog.json is missing");
    else if (fs.readFileSync(cat, "utf8") !== art.catalog.bytes) diffs.push("catalog.json is out of date");
    const bdir = path.join(dir, "bundles");
    const want = new Map(art.bundles.map((b) => [`${b.hash}.json`, b]));
    const have = fs.existsSync(bdir) ? fs.readdirSync(bdir).filter((f) => BUNDLE_FILE_RE.test(f)) : [];
    for (const [name, b] of want) {
        const file = path.join(bdir, name);
        if (!fs.existsSync(file)) diffs.push(`bundles/${name} (${b.id}) is missing`);
        else if (fs.readFileSync(file, "utf8") !== b.bytes) diffs.push(`bundles/${name} (${b.id}) doesn't match its hash`);
    }
    for (const f of have) if (!want.has(f)) diffs.push(`bundles/${f} is stale`);
    return diffs;
}

