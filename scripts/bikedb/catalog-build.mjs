/** Size shown in the picker, SI: displacement in m3 for petrol bikes, gross battery energy in J for EVs. */
function sizeOf(b) {
    if (b.powertrain === "ev") return b.battery && b.battery.grossCapacity ? Contract.toSI(b.battery.grossCapacity.v, b.battery.grossCapacity.u) : null;
    return b.engine && b.engine.displacement ? Contract.toSI(b.engine.displacement.v, b.engine.displacement.u) : null;
}

const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * catalog.json from search rows. Shared with the synthetic benchmark so it
 * measures exactly what ships.
 * @param {Array<{ id: string, make: string, model: string, variant: string|null, market: string, yearFrom: number, yearTo: number|null, classKey: string, size: number|null, aliases: string[], image_url: string|null, bundle: string }>} rows
 * @param {Array<{ key: string, powertrain: string, segment: string, title: string, image_url: string|null, bundle: string }>} classes
 * @param {string} schemaVersion
 */
export function assembleCatalog(rows, classes, schemaVersion) {
    const sorted = [...rows].sort((a, b) => byCode(a.make, b.make) || byCode(a.model, b.model) || byCode(a.variant || "", b.variant || "") || byCode(a.id, b.id));
    const makes = [...new Set(sorted.map((r) => r.make))].sort(byCode);
    const makeIdx = new Map(makes.map((m, i) => [m, i]));
    const classIdx = new Map(classes.map((c, i) => [c.key, i]));
    for (const r of sorted) if (!classIdx.has(r.classKey)) throw new BuildError(`${r.id}: class ${r.classKey} has no class default`);
    const column = {
        id: (r) => r.id, make: (r) => makeIdx.get(r.make), model: (r) => r.model, variant: (r) => r.variant, market: (r) => r.market,
        yearFrom: (r) => r.yearFrom, yearTo: (r) => r.yearTo, class: (r) => classIdx.get(r.classKey), size: (r) => r.size,
        aliases: (r) => r.aliases, image_url: (r) => (r.image_url === undefined ? null : r.image_url), bundle: (r) => r.bundle
    };
    const body = {
        format: Search.CATALOG_FORMAT,
        schemaVersion,
        units: "SI",
        bundlePath: BUNDLE_PATH,
        makes,
        classes,
        count: sorted.length,
        columns: Object.fromEntries(Search.CATALOG_COLUMNS.map((k) => [k, sorted.map(column[k])]))
    };
    const version = shortHash(canonicalJson(body));
    const catalog = { ...body, version };
    return { catalog, version, bytes: canonicalJson(catalog), rows: sorted };
}

