/**
 * Validate and build every artifact in memory. Throws BuildError (and writes
 * nothing) if the catalogue doesn't validate.
 * @param {{ entries: Array<{ file?: string, bundle: any }>, ref: any, calibrations?: Map<string, any> }} input  loadCatalog() output
 */
export function buildArtifacts({ entries, ref, calibrations = new Map() }) {
    const report = Contract.validateCatalog(entries, ref);
    if (!report.ok) {
        const details = [];
        for (const { file, result } of report.perFile) for (const e of result.errors) details.push(`${file} ${e.path}: ${e.message} [${e.code}]`);
        for (const e of report.errors) details.push(`${e.path}: ${e.message} [${e.code}]`);
        throw new BuildError("the bike catalogue doesn't validate — nothing was built (run node scripts/bikedb/validate.mjs)", details);
    }
    const warnings = report.warnings.length + report.perFile.reduce((n, p) => n + p.result.warnings.length, 0);

    const defaults = new Map(entries.filter((e) => e.bundle.kind === "class_default").map((e) => [e.bundle.classKey, e.bundle]));
    const classKeys = Object.entries(Contract.CLASS_MATRIX).flatMap(([pt, segs]) => segs.map((s) => `${pt}.${s}`));
    const variants = entries.filter((e) => e.bundle.kind === "variant").map((e) => e.bundle).sort((a, b) => byCode(a.id, b.id));

    /** @type {Array<{ id: string, kind: string, classKey: string, hash: string, bytes: string, runtime: any, source: any }>} */
    const bundles = [];
    const byHash = new Map();
    const add = (b, classDef) => {
        const runtime = makeRuntimeBundle(b, classDef, ref, calibrations.get(b.classKey) || null);
        const bytes = canonicalJson(runtime);
        const hash = shortHash(bytes);
        if (byHash.has(hash)) throw new BuildError(`bundle hash collision: ${b.id} and ${byHash.get(hash)} both hash to ${hash}`);
        byHash.set(hash, b.id);
        const out = { id: b.id, kind: b.kind, classKey: b.classKey, hash, bytes, runtime, source: b };
        bundles.push(out);
        return out;
    };
    const classes = classKeys.map((key) => {
        const d = defaults.get(key);
        const built = add(d, d);
        return { key, powertrain: d.powertrain, segment: d.segment, title: d.identity.model, image_url: d.image ? d.image.url : null, bundle: built.hash };
    });
    const rows = variants.map((b) => {
        const built = add(b, defaults.get(b.classKey));
        return {
            id: b.id, make: b.identity.make, model: b.identity.model, variant: b.identity.variant === undefined ? null : b.identity.variant,
            market: b.identity.market, yearFrom: b.identity.yearFrom, yearTo: b.identity.yearTo,
            classKey: b.classKey, size: sizeOf(b), aliases: b.identity.aliases, image_url: b.image ? b.image.url : null, bundle: built.hash
        };
    });
    const schemaVersion = Contract.SCHEMA_VERSION;
    const cat = assembleCatalog(rows, classes, schemaVersion);
    const gz = gzipSize(cat.bytes);
    if (gz > CATALOG_BUDGET_GZIP) throw new BuildError(`catalog.json is ${(gz / 1024).toFixed(1)} KB gzipped, over the ${CATALOG_BUDGET_GZIP / 1024} KB budget`);

    // Fingerprint of the INPUT (canonical, so formatting-only edits don't change it).
    const inputHash = sha256(canonicalJson({
        bundleFormat: BUNDLE_FORMAT, dbFormat: DB_FORMAT, schemaVersion,
        bundles: entries.map((e) => e.bundle).sort((a, b) => byCode(a.id, b.id)),
        ref,
        calibrations: [...calibrations.entries()].sort((a, b) => byCode(a[0], b[0]))
    }));
    return {
        bundles,
        catalog: { object: cat.catalog, bytes: cat.bytes, version: cat.version, rows: cat.rows, gzipBytes: gz },
        classes,
        inputHash,
        schemaVersion,
        counts: { variants: variants.length, classDefaults: classes.length, warnings }
    };
}

