const n0 = (x) => (x === undefined ? null : x);
const flag = (x) => (x ? 1 : 0);

/**
 * Build bikes.sqlite from the artifacts, into a temp file renamed into place
 * at the end, so a reader never sees a half-built database.
 * @param {ReturnType<typeof buildArtifacts>} art
 * @param {any} ref
 * @param {string} file
 * @param {{ name: string, open: (file: string, o?: any) => import("./sqlite-driver.mjs").Db }} driver
 */
export function writeSqlite(art, ref, file, driver) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const gi = path.join(path.dirname(file), ".gitignore");
    if (!fs.existsSync(gi)) fs.writeFileSync(gi, GITIGNORE);
    const tmp = `${file}.tmp-${process.pid}`;
    for (const f of [tmp, `${tmp}-journal`]) fs.rmSync(f, { force: true });
    const db = driver.open(tmp);
    let sqliteVersion;
    try {
        sqliteVersion = db.sqliteVersion;
        db.exec("PRAGMA page_size = 4096; PRAGMA journal_mode = DELETE; PRAGMA foreign_keys = ON;");
        db.exec(fs.readFileSync(SCHEMA_SQL, "utf8"));
        const uv = db.prepare("PRAGMA user_version").get();
        if (Number(Object.values(uv)[0]) !== DB_FORMAT) throw new BuildError(`lib/bikedb/schema.sql has user_version ${Object.values(uv)[0]}, but the build expects ${DB_FORMAT}`);
        db.transaction(() => fillDb(db, art, ref, sqliteVersion));
        const fk = db.prepare("PRAGMA foreign_key_check").all();
        if (fk.length) throw new BuildError("bikes.sqlite: foreign-key violations", fk.map((r) => JSON.stringify(r)));
        const ic = db.prepare("PRAGMA integrity_check").all().map((r) => Object.values(r)[0]);
        if (ic.length !== 1 || ic[0] !== "ok") throw new BuildError("bikes.sqlite: integrity check failed", ic.map(String));
        db.exec("INSERT INTO bundle_search(bundle_search) VALUES ('optimize');");
        db.exec("VACUUM;");
    } catch (e) {
        fs.rmSync(tmp, { force: true });
        throw e;
    } finally {
        try { db.close(); } catch { /* ignore */ }
    }
    try {
        fs.renameSync(tmp, file);
    } catch (e) {
        fs.rmSync(tmp, { force: true });
        if (e && (e.code === "EBUSY" || e.code === "EPERM")) throw new BuildError(`can't replace ${path.relative(ROOT, file)}: it's open in another program (stop the server and build again)`);
        throw e;
    }
    return { file, bytes: fs.statSync(file).size, driver: driver.name, sqliteVersion };
}

function fillDb(db, art, ref, sqliteVersion) {
    const ins = (sql) => db.prepare(sql);
    const meta = ins("INSERT INTO meta (key, value) VALUES (?, ?)");
    for (const [k, v] of [["db_format", String(DB_FORMAT)], ["schema_version", art.schemaVersion], ["bundle_format", BUNDLE_FORMAT],
        ["catalog_format", Search.CATALOG_FORMAT], ["catalog_version", art.catalog.version], ["input_hash", art.inputHash], ["sqlite_version", sqliteVersion]]) meta.run(k, v);

    const field = ins("INSERT INTO field (path, grp, value_type, unit, published_unit, si_factor, range_min, range_max, doc) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)");
    for (const f of Contract.FIELDS) {
        const q = f.type !== "c";
        field.run(f.path, f.path.split(".")[0], f.type, q ? Contract.siUnit(f.unit) : null, q ? f.unit : null, q ? Contract.toSI(1, f.unit) : null,
            f.range && q ? Contract.toSI(f.range[0], f.unit) : null, f.range && q ? Contract.toSI(f.range[1], f.unit) : null, f.doc);
    }

    const vclass = ins("INSERT INTO vehicle_class (class_key, powertrain, segment) VALUES (?, ?, ?)");
    for (const c of art.classes) vclass.run(c.key, c.powertrain, c.segment);

    // ---- reference tables ----
    const refSrc = ins("INSERT INTO ref_source (ref_table, source_key, ord, kind, title, url, publisher, retrieved, note) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)");
    for (const [table, t] of [["fuel-grades", ref.fuelGrades], ["emission-standards", ref.emissionStandards]]) {
        (t.sources || []).forEach((s, i) => refSrc.run(table, s.id, i, s.kind, s.title, n0(s.url), n0(s.publisher), s.retrieved, n0(s.note)));
    }
    const grade = ins("INSERT INTO fuel_grade (code, ord, ethanol_vol_fraction, flex_fuel_blend) VALUES (?, ?, ?, ?)");
    const gradeProp = ins("INSERT INTO fuel_grade_property (code, property, value, unit, published_value, published_unit, source_key, conf, note) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)");
    ref.fuelGrades.grades.forEach((g, i) => {
        grade.run(g.code, i, g.ethanolVolFraction, flag(g.flexFuelBlend));
        for (const p of ["lhv", "density", "typicalRon"]) {
            if (g[p]) gradeProp.run(g.code, p, Contract.toSI(g[p].v, g[p].u), Contract.siUnit(g[p].u), g[p].v, g[p].u, g[p].src, g[p].conf, n0(g[p].note));
        }
    });
    const obd = ins("INSERT INTO obd_level (code, name, effective_from, source_key, conf, note) VALUES (?, ?, ?, ?, ?, ?)");
    for (const o of ref.emissionStandards.obdLevels) obd.run(o.code, o.name, o.effectiveFrom, o.src, o.conf, n0(o.note));
    const std = ins("INSERT INTO emission_standard (code, name, region, effective_from, superseded_from, obd_at_intro, source_key, conf, note) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)");
    for (const s of ref.emissionStandards.standards) std.run(s.code, s.name, s.region, s.effectiveFrom, n0(s.supersededFrom), n0(s.obdAtIntro), s.src, s.conf, n0(s.note));

    // ---- makes and models (variants only) ----
    const makeId = new Map(), modelId = new Map();
    const mk = ins("INSERT INTO make (make_id, name) VALUES (?, ?)");
    const md = ins("INSERT INTO model (model_id, make_id, name) VALUES (?, ?, ?)");
    for (const name of art.catalog.object.makes) { makeId.set(name, makeId.size + 1); mk.run(makeId.size, name); }
    for (const r of art.catalog.rows) {
        const key = `${r.make}\u0000${r.model}`;
        if (!modelId.has(key)) { modelId.set(key, modelId.size + 1); md.run(modelId.size, makeId.get(r.make), r.model); }
    }

    // ---- bundles: class defaults (class order), then variants (catalogue order) ----
    const order = [...art.bundles.filter((b) => b.kind === "class_default"),
        ...art.catalog.rows.map((r) => art.bundles.find((b) => b.id === r.id))];
    const bundle = ins("INSERT INTO bundle (bundle_id, slug, kind, class_key, model_id, variant_name, title, market, year_from, year_to, schema_version, image_url, hash, body) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)");
    const cdef = ins("INSERT INTO class_default (class_key, bundle_id) VALUES (?, ?)");
    const alias = ins("INSERT INTO alias (bundle_id, ord, alias) VALUES (?, ?, ?)");
    const source = ins("INSERT INTO source (bundle_id, source_key, ord, kind, title, url, publisher, retrieved, note) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)");
    const spec = ins(`INSERT INTO spec_value (bundle_id, path, value, vals, txt, flag, tol, qualifier, source_key, conf, note, published_value, published_vals, published_tol)
                      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`);
    const prior = ins("INSERT INTO prior (bundle_id, path, mean, sigma, source_key, conf, note, published_mean, published_sigma) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)");
    const curve = ins(`INSERT INTO curve (bundle_id, kind, omega_start, omega_step, scale, unit, published_rpm_start, published_rpm_step, published_scale, published_unit, data, method, source_key, conf, note)
                       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`);
    const note = ins("INSERT INTO note (bundle_id, ord, text) VALUES (?, ?, ?)");
    const compat = ins("INSERT INTO fuel_compat (bundle_id, fuel_code, ord, status, source_key, conf, note, advisable) VALUES (?, ?, ?, ?, ?, ?, ?, ?)");
    const fts = ins("INSERT INTO bundle_search (rowid, make, model, variant, aliases) VALUES (?, ?, ?, ?, ?)");

    order.forEach((art_b, i) => {
        const id = i + 1;
        const b = art_b.source;
        const idn = b.identity;
        const isVariant = b.kind === "variant";
        const title = [idn.make, idn.model, idn.variant].filter(Boolean).join(" ");
        bundle.run(id, b.id, b.kind, b.classKey, isVariant ? modelId.get(`${idn.make}\u0000${idn.model}`) : null, n0(idn.variant), title,
            idn.market, idn.yearFrom, idn.yearTo, b.schemaVersion, b.image ? b.image.url : null, art_b.hash, art_b.bytes);
        if (!isVariant) cdef.run(b.classKey, id);
        idn.aliases.forEach((a, j) => alias.run(id, j, a));
        b.sources.forEach((s, j) => source.run(id, s.id, j, s.kind, s.title, n0(s.url), n0(s.publisher), s.retrieved, n0(s.note)));
        for (const f of Contract.FIELDS) {
            const [g, k] = f.path.split(".");
            const v = b[g] && b[g][k];
            if (!v) continue;
            if (f.type === "p") {
                prior.run(id, f.path, Contract.toSI(v.mean, f.unit), Contract.toSI(v.sigma, f.unit), v.src, v.conf, n0(v.note), v.mean, v.sigma);
                continue;
            }
            const extraKey = Object.keys(f.extra || {})[0];
            const q = f.type === "q", qa = f.type === "qa", cat = f.type === "c";
            spec.run(id, f.path,
                q ? Contract.toSI(v.v, f.unit) : null,
                qa ? JSON.stringify(Contract.toSI(v.v, f.unit)) : null,
                cat && typeof v.v !== "boolean" ? v.v : null,
                cat && typeof v.v === "boolean" ? flag(v.v) : null,
                v.tol !== undefined ? Contract.toSI(v.tol, f.unit) : null,
                extraKey ? v[extraKey] : null, v.src, v.conf, n0(v.note),
                q ? v.v : null, qa ? JSON.stringify(v.v) : null, n0(v.tol));
        }
        for (const [kind, c] of Object.entries(b.curves || {})) {
            curve.run(id, kind, Contract.toSI(c.rpmStart, "rpm"), Contract.toSI(c.rpmStep, "rpm"), Contract.toSI(c.scale, c.u), Contract.siUnit(c.u),
                c.rpmStart, c.rpmStep, c.scale, c.u, JSON.stringify(c.data), c.method, c.src, c.conf, n0(c.note));
        }
        (b.notes || []).forEach((t, j) => note.run(id, j, t));
        const advisable = new Set((art_b.runtime.fuelAdvice && art_b.runtime.fuelAdvice.advisable) || []);
        ((b.fuel && b.fuel.compat) || []).forEach((c, j) => compat.run(id, c.fuel, j, c.status, c.src, c.conf, n0(c.note), flag(advisable.has(c.fuel))));
        if (isVariant) {
            const row = art.catalog.rows.find((r) => r.id === b.id);
            fts.run(id, ...Search.ftsColumns(row));
        }
    });
}

/**
 * Is bikes.sqlite up to date with this build? (Compares the input fingerprint,
 * not bytes, because a different SQLite version writes different bytes.)
 * @returns {string[]} differences
 */
export function diffSqlite(art, file, driver) {
    if (!fs.existsSync(file)) return [`${path.relative(ROOT, file)} is missing`];
    const db = driver.open(file, { readonly: true });
    try {
        const meta = Object.fromEntries(db.prepare("SELECT key, value FROM meta").all().map((r) => [r.key, r.value]));
        const diffs = [];
        if (meta.db_format !== String(DB_FORMAT)) diffs.push(`bikes.sqlite has db format ${meta.db_format}, expected ${DB_FORMAT}`);
        if (meta.input_hash !== art.inputHash) diffs.push("bikes.sqlite was built from different data");
        if (meta.catalog_version !== art.catalog.version) diffs.push("bikes.sqlite has a different catalog version");
        return diffs;
    } catch (e) {
        return [`bikes.sqlite can't be read: ${e.message}`];
    } finally { db.close(); }
}

// ----------------------------------------------------------------------------
// Convenience: the whole build
// ----------------------------------------------------------------------------
/**
 * @param {{ dataDir?: string, publicDir?: string, dbFile?: string, skipSqlite?: boolean, prune?: boolean, driver?: string }} [opts]
 */
export async function build(opts = {}) {
    const input = loadCatalog(opts.dataDir || DATA);
    const art = buildArtifacts(input);
    // Load the SQLite driver before writing anything, so a missing driver fails cleanly.
    let driver = null;
    if (!opts.skipSqlite) driver = (await import("./sqlite-driver.mjs")).loadDriver({ driver: opts.driver });
    const pub = writePublic(art, opts.publicDir || DEFAULT_PUBLIC_DIR, { prune: opts.prune !== false });
    const db = driver ? writeSqlite(art, input.ref, opts.dbFile || DEFAULT_DB_FILE, driver) : null;
    return { art, pub, db };
}

/** catalog.json + bundles only (no SQLite) — used by scripts/build-native.mjs. */
export function buildPublicOnly(opts = {}) {
    const art = buildArtifacts(loadCatalog(opts.dataDir || DATA));
    return { art, pub: writePublic(art, opts.publicDir || DEFAULT_PUBLIC_DIR, { prune: opts.prune !== false }) };
}
